import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sourceDirectory = path.join(root, "src", "specialists", "assets");
const target = path.join(root, "src", "specialists", "embedded-assets.ts");

/** Build-time generation: no runtime asset lookup or network dependency. */
export async function generateSpecialistAssets(): Promise<string> {
  const entries: Array<[string, string]> = [];
  async function visit(dir: string, relative = ""): Promise<void> {
    const children = await readdir(dir, { withFileTypes: true });
    for (const child of children) {
      const next = path.posix.join(relative, child.name);
      if (child.isDirectory()) await visit(path.join(dir, child.name), next);
      else if (child.isFile() && next.endsWith(".md")) {
        entries.push([next, await readFile(path.join(dir, child.name), "utf8")]);
      } else {
        throw new Error("Unexpected Specialist asset: " + next);
      }
    }
  }
  await visit(sourceDirectory);
  entries.sort((a, b) => a[0].localeCompare(b[0]));
  if (entries.length !== 14) throw new Error("Expected 12 Workspace fragments and 2 Shopping Procedures");
  return "// Generated from src/specialists/assets/**.md. Run bun scripts/generate-specialist-assets.ts.\n" +
    "// Do not edit this file by hand. Assets are bundled as TypeScript strings for npm/standalone binaries.\n" +
    "export const SPECIALIST_ASSETS: Readonly<Record<string, string>> = " +
    JSON.stringify(Object.fromEntries(entries), null, 2) + ";\n";
}

async function main(): Promise<void> {
  const expected = await generateSpecialistAssets();
  if (process.argv.includes("--check")) {
    const actual = await readFile(target, "utf8");
    if (actual !== expected) throw new Error("Embedded assets are stale: regenerate from Markdown sources");
    process.stdout.write("Specialist embedded assets match Markdown sources.\n");
  } else await writeFile(target, expected, "utf8");
}

const isEntrypoint = process.argv[1] !== undefined &&
  import.meta.url === pathToFileURL(process.argv[1]).href;
if (isEntrypoint) await main();
